package org.sandbot.sdk.devices;

import com.qualcomm.robotcore.hardware.HardwareMap;

import org.sandbot.sim.HubTiming;
import org.sandbot.sim.Sim;
import org.sandbot.sim.SimClock;
import org.sandbot.sim.SimDevice;
import org.sandbot.sim.SimHost;
import org.sandbot.sim.TelemetryFrame;

import java.io.File;
import java.io.IOException;
import java.io.OutputStreamWriter;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Map;

/**
 * 장치 시험 도구: 런타임의 VirtualClock 대신 가짜 시계(charge·sleep이 나노초를 더하기만 함)를 한 번 설치한다
 * (Sim.install은 JVM마다 한 번). 시험마다 이름이 겹치지 않게 접두어를 붙인 구성 XML을 만든다(SimDevices는 JVM 전체에 하나).
 */
final class SimTestSupport {
    private SimTestSupport() {}

    static final class FakeClock implements SimClock {
        long nanos = 0;

        @Override public long nanoTime() {
            return nanos;
        }

        @Override public long currentTimeMillis() {
            return 1_700_000_000_000L + nanos / 1_000_000L;
        }

        @Override public void charge(long n) {
            nanos += n;
        }

        @Override public void sleep(long n) throws InterruptedException {
            if (Thread.interrupted()) throw new InterruptedException();
            if (n > 0) nanos += n;
        }

        @Override public void awaitNextTick() throws InterruptedException {
            sleep(tickNanos() - nanos % tickNanos());
        }

        @Override public long tickNanos() {
            return 5_000_000L;
        }
    }

    static final class FakeHost implements SimHost {
        final List<String> logs = Collections.synchronizedList(new ArrayList<String>());

        @Override public void telemetry(TelemetryFrame frame) {
        }

        @Override public void log(String stream, String text) {
            logs.add(stream + ": " + text);
        }

        @Override public void loopMarker() {
        }
    }

    static final FakeClock CLOCK = new FakeClock();
    private static int counter = 0;

    static synchronized void install() {
        if (!Sim.installed()) Sim.install(CLOCK, HubTiming.defaults(), new FakeHost());
    }

    /** 이번 시험의 이름 접두어 */
    static synchronized String prefix() {
        install();
        return "t" + (++counter) + ".";
    }

    static long now() {
        return CLOCK.nanos;
    }

    /** body를 돌리는 동안 흐른 가상 시간(ns) */
    static long elapsed(Runnable body) {
        long start = CLOCK.nanos;
        body.run();
        return CLOCK.nanos - start;
    }

    static long ms(double millis) {
        return Math.round(millis * 1_000_000.0);
    }

    static File writeXml(String xml) {
        try {
            File file = Files.createTempFile("sandbot-config", ".xml").toFile();
            file.deleteOnExit();
            try (Writer w = new OutputStreamWriter(Files.newOutputStream(file.toPath()), StandardCharsets.UTF_8)) {
                w.write(xml);
            }
            return file;
        } catch (IOException e) {
            throw new RuntimeException(e);
        }
    }

    /** configXml.ts가 만드는 모양의 구성(허브 이름·장치 이름에 접두어 p) */
    static String robotXml(String p, String expansionDevices, String controlDevices, String usbDevices) {
        StringBuilder xml = new StringBuilder();
        xml.append("<?xml version='1.0' encoding='UTF-8' standalone='yes' ?>\n");
        xml.append("<!-- Generated by SandBot. -->\n");
        xml.append("<Robot type=\"FirstInspires-FTC\" name=\"Test Bot\">\n");
        xml.append("    <LynxUsbDevice name=\"Control Hub Portal\" serialNumber=\"(embedded)\" parentModuleAddress=\"173\">\n");
        if (expansionDevices != null) {
            xml.append("        <LynxModule name=\"").append(p).append("Expansion Hub 2\" port=\"2\">\n");
            xml.append(expansionDevices.replace("name=\"", "name=\"" + p));
            xml.append("        </LynxModule>\n");
        }
        xml.append("        <LynxModule name=\"").append(p).append("Control Hub\" port=\"173\">\n");
        xml.append(controlDevices.replace("name=\"", "name=\"" + p));
        xml.append("        </LynxModule>\n");
        xml.append("    </LynxUsbDevice>\n");
        if (usbDevices != null) xml.append(usbDevices.replace("name=\"", "name=\"" + p));
        xml.append("</Robot>\n");
        return xml.toString();
    }

    static HardwareMap create(String xml) {
        try {
            return SandbotHardware.create(writeXml(xml));
        } catch (SandbotConfigException e) {
            throw new RuntimeException(e);
        }
    }

    static SimDevice device(String name) {
        SimDevice d = Sim.devices().get(name);
        if (d == null) throw new AssertionError("no simulated device " + name);
        return d;
    }

    static void input(String name, String key, Object value) {
        device(name).applyInputs(Collections.singletonMap(key, value));
    }

    static Object output(String name, String key) {
        Map<String, Object> outputs = device(name).outputs();
        if (!outputs.containsKey(key)) throw new AssertionError(name + " has no output " + key + ": " + outputs);
        return outputs.get(key);
    }
}
